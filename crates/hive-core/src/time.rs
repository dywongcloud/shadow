//! Tiny time helpers. We store timestamps as unix-epoch milliseconds so they
//! serialize cleanly and are cheap to compare.

use std::time::{SystemTime, UNIX_EPOCH};

pub fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}
